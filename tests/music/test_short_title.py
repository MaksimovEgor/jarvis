import pytest

from app.music.models import short_title



@pytest.mark.parametrize("title, spoken", [
    ("🚌 Малютка автобус, который боялся темноты — Дональд Биссет | Сказка для детей. Читает Сергей Страхов",
     "Малютка автобус, который боялся темноты — Дональд Биссет"),
    ("БОРОНИНА - ЗАЖИГАЛКА /// ВЫПУСКНОЙ В КРОКУСЕ 2019", "БОРОНИНА - ЗАЖИГАЛКА"),
    ("Foo Fighters - Everlong", "Foo Fighters - Everlong"),
    ("Сказка про Автобус * Аудиосказка для мальчиков *", "Сказка про Автобус"),
    ("Сборник русских народных сказок. Читают Литвинов, Румянова, Пельтцер и другие артисты (1970-80-е)",
     "Сборник русских народных сказок. Читают Литвинов, Румянова, Пельтцер…"),
])
def test_short_title(title: str, spoken: str) -> None:
    assert short_title(title) == spoken
